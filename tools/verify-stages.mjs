import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const call=async(name,body={})=>{
 const response=await fetch('http://127.0.0.1:8085/api/'+name,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
 const data=await response.json();
 if(!response.ok)throw new Error(data.error);
 return data;
};
const stages=await call('liststages');
assert.deepEqual(stages.map(s=>s.enemies),[15,30,50]);
const guest=await call('createguest',{nickname:'关卡验收'});
const auth={userToken:guest.token};
const start=stageId=>call('startrun',{...auth,characterId:'amber',requestId:randomUUID(),stageId});
await assert.rejects(()=>start('missing'));
const stage=await start('forest');
assert.equal(stage.stage.enemies,15);
const failure=await call('submitrunresult',{...auth,runId:stage.runId,kills:0,ticks:1});
assert.equal(failure.primogems,1600);
assert.equal(failure.mora,5000);
const win=await start('forest');
await new Promise(resolve=>setTimeout(resolve,6500));
const result={...auth,runId:win.runId,kills:15,ticks:180};
await Promise.all([call('submitrunresult',result),call('submitrunresult',result)]);
const profile=await call('getprofile',auth);
assert.equal(profile.primogems,1640);
assert.equal(profile.mora,5300);
const original=await start(null);
assert.equal(original.stage,null);
const legacy=await call('submitrunresult',{...auth,runId:original.runId,kills:0,ticks:1});
assert.equal(legacy.primogems,1640);
assert.equal(legacy.mora,5300);
