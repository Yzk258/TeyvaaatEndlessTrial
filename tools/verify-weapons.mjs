import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import fs from 'node:fs';
const catalog=JSON.parse(fs.readFileSync(new URL('../shared/weapons.json',import.meta.url),'utf8'));
const call=async(name,body={})=>{
 const response=await fetch('http://127.0.0.1:8085/api/'+name,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
 const data=await response.json();
 if(!response.ok)throw new Error(data.error);
 return data;
};
const definitions=await call('listweapons');
assert.equal(definitions.length,15);
assert.deepEqual(definitions,catalog);
assert.equal(new Set(definitions.map(w=>w.weapon)).size,5);
assert.deepEqual([3,4,5].map(rarity=>definitions.filter(w=>w.rarity===rarity).length),[5,5,5]);
