assert.deepEqual(wishes[0],wishes[1]);
assert.equal(wishes[0].reward.kind,'weapon');
assert.equal(wishes[0].profile.primogems,1600);
assert.equal(wishes[0].profile.intertwinedFates,9);
assert.equal(wishes[0].profile.pity,0);
assert.equal(wishes[0].profile.fourStarPity,0);
assert.equal(wishes[0].profile.weaponPity,wishes[0].reward.rarity===5?0:1);
const weaponId=wishes[0].reward.id;
const level={...auth,weaponId,requestId:randomUUID()};
await Promise.all([call('levelupweapon',level),call('levelupweapon',level)]);
const profile=await call('getprofile',auth);
assert.equal(profile.mora,4700);
assert.equal(profile.weapons.find(w=>w.id===weaponId).level,2);
await assert.rejects(()=>call('levelupweapon',{...level,weaponId:'missing'}));
const other=await call('createguest',{nickname:'武器隔离验收'});
await assert.rejects(()=>call('levelupweapon',{userToken:other.token,weaponId,requestId:randomUUID()}));
