await durationInput('60');
await waitFor(`[...document.querySelectorAll('button')].some(b=>b.textContent.trim()==='开始限时冒险 →'&&!b.disabled)`);
await screenshot('adventure-custom');
await click('开始限时冒险 →');
await waitFor(`document.body.textContent.includes('低语森林 · 限时冒险')`);
