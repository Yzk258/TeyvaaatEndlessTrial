import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const base='http://127.0.0.1:8085/api/';
const call=async(name,body={})=>{
  const response=await fetch(base+name,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const data=await response.json();
  if(!response.ok)throw new Error(data.error);
  return data;
};
const guest=await call('createguest',{nickname:'验收旅行者'});
const auth={userToken:guest.token};
const initial=await call('getprofile',auth);
assert.equal(initial.primogems,1600);
assert.equal(initial.mora,5000);
assert.equal(initial.characters[0].id,'amber');
const wish={...auth,requestId:randomUUID()};
const results=await Promise.all([call('performwish',wish),call('performwish',wish)]);
assert.deepEqual(results[0],results[1]);
assert.equal((await call('getprofile',auth)).primogems,1600);
assert.equal((await call('getprofile',auth)).intertwinedFates,9);
const level={...auth,characterId:'amber',requestId:randomUUID()};
await Promise.all([call('levelupcharacter',level),call('levelupcharacter',level)]);
assert.equal((await call('getprofile',auth)).mora,4500);
await assert.rejects(()=>call('levelupcharacter',{...level,characterId:'invalid'}));
const run=await call('startrun',{...auth,characterId:'amber',requestId:randomUUID()});
const other=await call('createguest',{nickname:'另一个旅行者'});
await assert.rejects(()=>call('submitrunresult',{userToken:other.token,runId:run.runId,kills:0,ticks:1}));
const settlement={...auth,runId:run.runId,kills:0,ticks:1};
await Promise.all([call('submitrunresult',settlement),call('submitrunresult',settlement)]);
const profile=await call('getprofile',auth);
assert.equal(profile.runs,1);
assert.equal(profile.primogems,1600);
assert.equal(profile.mora,4500);
await assert.rejects(()=>call('submitrunresult',{...settlement,kills:1}));
await Promise.all(Array.from({length:12},()=>call('performwish',{...auth,requestId:randomUUID()}).then(()=>true,()=>false)));
const spent=await call('getprofile',auth);
assert.equal(spent.primogems,1600);
assert.equal(spent.intertwinedFates,0);
assert.equal([...spent.characters,...spent.weapons].reduce((sum,item)=>sum+1+item.copies,0),11);
const definitions=await call('listcharacters');
assert.ok(spent.characters.every(c=>definitions.some(d=>d.id===c.id)));
